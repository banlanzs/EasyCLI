// ---- i18n core ----

const I18N_DEFAULT_LANG = 'zh';
const I18N_STORAGE_KEY = 'easycli-lang';

const i18n = {
  _lang: I18N_DEFAULT_LANG,

  init() {
    const saved = localStorage.getItem(I18N_STORAGE_KEY);
    this._lang = saved || I18N_DEFAULT_LANG;
  },

  setLang(lang) {
    if (!I18N_TRANSLATIONS[lang]) return;
    this._lang = lang;
    localStorage.setItem(I18N_STORAGE_KEY, lang);
    this.applyToDOM();
  },

  getLang() {
    return this._lang;
  },

  t(key, fallback) {
    const dict = I18N_TRANSLATIONS[this._lang] || I18N_TRANSLATIONS[I18N_DEFAULT_LANG];
    if (dict[key] !== undefined) return dict[key];
    if (I18N_TRANSLATIONS.en[key] !== undefined) return I18N_TRANSLATIONS.en[key];
    return fallback !== undefined ? fallback : key;
  },

  applyToDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.getAttribute('data-i18n-title'));
    });
  }
};

i18n.init();
document.addEventListener('DOMContentLoaded', () => i18n.applyToDOM());
